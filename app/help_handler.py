# окно «Справка» в интерфейсе.

from app.core.identity_matrix import IDENTITY_MATRIX
from app.language.vocabulary.phrases import HELP_COMMANDS


def get_skill_lines() -> list[str]:
    """Возвращает навыки ядра одной строкой на навык."""

    return [
        f"{skill['name']}: {skill['description']}"
        for skill in IDENTITY_MATRIX["skills"]
    ]


def get_question_lines() -> list[str]:
    """Возвращает обычные вопросы и команды, которые понимает ядро."""

    return [
        "как меня зовут",
        "сколько сейчас времени",
        "какая сегодня дата",
        "какой сегодня день недели",
        "посчитать выражение: 2 + 2",
        "выход",
    ]


