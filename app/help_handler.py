def get_help_sections() -> list[tuple[str, list[str]]]:
    """Собирает полную справку по разделам: заголовок и список пунктов.

    Один источник и для консольного ответа на «помощь», и для окна
    «Справка» — список команд не расходится между ними.
    """

    return [
        ("Я умею", get_skill_lines()),
        ("Обычные вопросы и команды", get_question_lines()),
        ("Системные команды", get_system_command_lines()),
    ]


def get_help_response(message: str) -> str | None:
    """Возвращает справку по командам и навыкам."""

    if not any(
        command in message
        for command in HELP_COMMANDS
    ):
        return None

    lines = []

    for title, items in get_help_sections():
        lines.append(f"{title}:")

        for item in items:
            lines.append(f"- {item}")

        lines.append("")

    return "\n".join(lines).rstrip()
